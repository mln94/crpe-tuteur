-- Quiz CRPE réintégré dans le projet « crpe » : un seul compte et une seule authentification pour le tuteur IA et le quiz.
-- Les identifiants des questions sont ceux du projet « quizzcrpe » (copie identique), la progression des navigateurs reste valable.
-- Lecture et écriture réservées au serveur (clé service_role) : RLS activée sans politique.

create table if not exists public.quiz_questions (
  id bigint generated by default as identity primary key,
  matiere text not null check (matiere in ('francais','mathematiques','histoire_geographie','emc','svt','physique_chimie','technologie','arts','anglais')),
  ordre integer not null default 0,
  question text not null,
  choix jsonb not null,
  reponse text not null,
  explication text not null,
  actif boolean not null default true,
  created_at timestamptz not null default now(),
  niveau text check (niveau in ('facile','intermediaire','difficile')),
  type text not null default 'qcm' check (type in ('qcm','numerique','cliquer_mot')),
  notion text,
  programme_ref text,
  classe text,
  theme text,
  sous_theme text,
  objectif text,
  tolerance numeric not null default 0,
  constraint quiz_questions_choix_check check (jsonb_typeof(choix) = 'array' and (type <> 'qcm' or jsonb_array_length(choix) between 2 and 6)),
  constraint quiz_questions_reponse_dans_choix check (type <> 'qcm' or choix ? reponse)
);
create index if not exists quiz_questions_matiere_idx on public.quiz_questions (matiere) where actif;
create index if not exists quiz_questions_matiere_notion_idx on public.quiz_questions (matiere, notion) where actif;
alter table public.quiz_questions enable row level security;

create table if not exists public.programme_cycle4_disciplines (
  id bigint generated by default as identity primary key,
  matiere text not null,
  code text not null,
  classe text,
  theme text not null,
  sous_theme text not null,
  objectifs jsonb not null check (jsonb_typeof(objectifs) = 'array'),
  source text not null,
  created_at timestamptz not null default now(),
  unique (matiere, code)
);
alter table public.programme_cycle4_disciplines enable row level security;

-- Accès au quiz par compte : test de positionnement et paiement (le tuteur IA garde profils_utilisateurs.crpe_paid)
create table if not exists public.quiz_comptes (
  user_id uuid primary key references auth.users (id) on delete cascade,
  email text,
  positionnement jsonb,
  positionnement_at timestamptz,
  paid boolean not null default false,
  paid_at timestamptz,
  paypal_ref text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.quiz_comptes enable row level security;
