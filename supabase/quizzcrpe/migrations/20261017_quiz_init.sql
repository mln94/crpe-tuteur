-- Projet Supabase « quizzcrpe » (uwsdfbmootumhsrufkmo) : tables du Quiz CRPE, séparées du projet « crpe ».
-- Les identifiants des questions sont repris du projet crpe : la progression gardée dans le navigateur reste valable.
-- Accès : RLS activée sans politique ; le serveur passe uniquement par les deux fonctions ci-dessous.

create table if not exists public.quiz_questions (
  id bigint generated by default as identity primary key,
  matiere text not null check (matiere in ('francais','mathematiques','histoire_geographie','emc','svt','physique_chimie','technologie','arts','anglais')),
  ordre integer not null default 0,
  question text not null,
  choix jsonb not null,
  reponse text not null,
  explication text not null,
  actif boolean not null default true,
  created_at timestamptz not null default now(),
  niveau text check (niveau in ('facile','intermediaire','difficile')),
  type text not null default 'qcm' check (type in ('qcm','numerique','cliquer_mot')),
  notion text,
  programme_ref text,
  classe text,
  theme text,
  sous_theme text,
  objectif text,
  tolerance numeric not null default 0,
  constraint quiz_questions_choix_check check (jsonb_typeof(choix) = 'array' and (type <> 'qcm' or jsonb_array_length(choix) between 2 and 6)),
  constraint quiz_questions_reponse_dans_choix check (type <> 'qcm' or choix ? reponse)
);
create index if not exists quiz_questions_matiere_idx on public.quiz_questions (matiere) where actif;
create index if not exists quiz_questions_matiere_notion_idx on public.quiz_questions (matiere, notion) where actif;
alter table public.quiz_questions enable row level security;

-- Référentiel des programmes du cycle 4 (hors français et maths), source : scripts/quiz/referentiel.py
create table if not exists public.programme_cycle4_disciplines (
  id bigint generated by default as identity primary key,
  matiere text not null,
  code text not null,
  classe text,
  theme text not null,
  sous_theme text not null,
  objectifs jsonb not null check (jsonb_typeof(objectifs) = 'array'),
  source text not null,
  created_at timestamptz not null default now(),
  unique (matiere, code)
);
alter table public.programme_cycle4_disciplines enable row level security;

-- Catalogue d'une matière, sans les réponses
create or replace function public.quiz_catalogue(p_matiere text)
returns table (id bigint, notion text, niveau text, type text, question text, choix jsonb,
               programme_ref text, classe text, theme text, sous_theme text, objectif text)
language sql stable security definer set search_path = public as $$
  select q.id, q.notion, q.niveau, q.type, q.question, q.choix, q.programme_ref, q.classe, q.theme, q.sous_theme, q.objectif
  from public.quiz_questions q where q.matiere = p_matiere and q.actif order by q.ordre, q.id;
$$;

-- Réponse attendue d'une seule question, pour la correction (renvoyée de toute façon après la réponse de l'élève)
create or replace function public.quiz_correction(p_id bigint)
returns table (type text, choix jsonb, reponse text, explication text, tolerance numeric)
language sql stable security definer set search_path = public as $$
  select q.type, q.choix, q.reponse, q.explication, q.tolerance from public.quiz_questions q where q.id = p_id and q.actif;
$$;

revoke all on function public.quiz_catalogue(text) from public;
revoke all on function public.quiz_correction(bigint) from public;
grant execute on function public.quiz_catalogue(text) to anon, authenticated, service_role;
grant execute on function public.quiz_correction(bigint) to anon, authenticated, service_role;
